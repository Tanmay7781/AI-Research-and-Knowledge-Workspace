-- =====================================================================
-- Actual PostgreSQL Schema Reference for AI Research and Knowledge Workspace
-- Database: ai_knowledge_workspace
-- =====================================================================
-- NOTE:
-- All primary keys use UUIDs generated via gen_random_uuid().
-- The actual running database uses UUID identifiers (NOT SERIAL/INTEGER).
-- Do NOT convert UUIDs to integers.
-- =====================================================================

-- 0. Enable pgcrypto for UUID generation if not already enabled
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- 1. Users Table (prepared for user workspace isolation / authentication)
CREATE TABLE IF NOT EXISTS users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name VARCHAR(255),
    email VARCHAR(255) UNIQUE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 2. Workspaces Table
-- Organizes documents into isolated knowledge workspaces.
-- A default workspace exists with UUID 'f6b44e12-aa38-4041-a20f-d900e52bb650'.
CREATE TABLE IF NOT EXISTS workspaces (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID REFERENCES users(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL DEFAULT 'Default Workspace',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 3. Documents Table
-- Tracks uploaded PDF metadata, local filesystem storage path, extracted text, and lifecycle status.
-- IMPORTANT: This table uses 'created_at' and 'analyzed_at'. There is NO 'updated_at' column.
CREATE TABLE IF NOT EXISTS documents (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    workspace_id UUID REFERENCES workspaces(id) ON DELETE SET NULL,
    original_filename VARCHAR(255) NOT NULL,
    stored_filename VARCHAR(255) NOT NULL,
    file_path TEXT NOT NULL,
    file_size BIGINT,
    mime_type VARCHAR(255) DEFAULT 'application/pdf',
    extracted_text TEXT,
    status VARCHAR(50) NOT NULL DEFAULT 'uploaded', -- 'uploaded', 'processing', 'analyzed', 'failed'
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    analyzed_at TIMESTAMP WITH TIME ZONE
);

-- 4. Document Analyses Table
-- Stores structured AI analysis generated by Google Gemini.
-- The UNIQUE constraint on document_id enforces strict 1:1 relationship with duplicate protection.
CREATE TABLE IF NOT EXISTS document_analyses (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    document_id UUID UNIQUE NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    summary TEXT,
    key_points JSONB NOT NULL DEFAULT '[]'::jsonb,
    flashcards JSONB NOT NULL DEFAULT '[]'::jsonb,
    quiz_questions JSONB NOT NULL DEFAULT '[]'::jsonb,
    important_terms JSONB NOT NULL DEFAULT '[]'::jsonb,
    model_name VARCHAR(255) DEFAULT 'gemini-2.5-flash',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 5. Document Chunks Table (RAG Vector Knowledge Base)
-- Stores extracted chunks with page numbers, chunk order, and 768-dimensional embeddings
-- generated via Google text-embedding-004.
-- In standard PostgreSQL, embedding is stored as real[] with cosine_similarity function.
-- If pgvector extension is installed, can be stored or cast as vector(768).
CREATE TABLE IF NOT EXISTS document_chunks (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    document_id UUID NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    chunk_index INTEGER NOT NULL,
    content TEXT NOT NULL,
    page_number INTEGER,
    embedding REAL[], -- 768 dimensions for text-embedding-004
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- Cosine similarity helper function for native PostgreSQL vector search without external plugins:
CREATE OR REPLACE FUNCTION cosine_similarity(a REAL[], b REAL[])
RETURNS DOUBLE PRECISION AS $$
DECLARE
    dot_product DOUBLE PRECISION := 0;
    norm_a DOUBLE PRECISION := 0;
    norm_b DOUBLE PRECISION := 0;
    i INT;
    len INT;
BEGIN
    len := array_length(a, 1);
    IF len IS NULL OR len <> array_length(b, 1) THEN
        RETURN 0;
    END IF;
    FOR i IN 1..len LOOP
        dot_product := dot_product + (a[i] * b[i]);
        norm_a := norm_a + (a[i] * a[i]);
        norm_b := norm_b + (b[i] * b[i]);
    END LOOP;
    IF norm_a = 0 OR norm_b = 0 THEN
        RETURN 0;
    END IF;
    RETURN dot_product / (sqrt(norm_a) * sqrt(norm_b));
END;
$$ LANGUAGE plpgsql IMMUTABLE;

-- Indexes for performance
CREATE INDEX IF NOT EXISTS idx_documents_workspace_id ON documents(workspace_id);
CREATE INDEX IF NOT EXISTS idx_documents_status ON documents(status);
CREATE INDEX IF NOT EXISTS idx_document_analyses_document_id ON document_analyses(document_id);
CREATE INDEX IF NOT EXISTS idx_document_chunks_document_id ON document_chunks(document_id);
CREATE INDEX IF NOT EXISTS idx_document_chunks_doc_chunk ON document_chunks(document_id, chunk_index);

